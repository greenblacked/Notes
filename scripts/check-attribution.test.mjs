import assert from "node:assert/strict"
import { execFileSync } from "node:child_process"
import { mkdtempSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { test } from "node:test"
import {
  commitProblems,
  eventProblems,
  main,
  parseLog,
  rangeArgs,
  textProblems,
} from "./check-attribution.mjs"

// Built from parts so this file never contains the phrases it forbids in commit messages.
const V = ["cla", "ude"].join("")
const A = ["anthr", "opic"].join("")

test("tool co-author trailers are flagged, dependabot ones are not", () => {
  assert.equal(textProblems("m", `fix\n\nCo-Authored-By: ${V} <x@y>`).length, 1)
  assert.equal(textProblems("m", `fix\n\nco-authored-by: Someone ${A}`).length, 1)
  assert.equal(
    textProblems(
      "m",
      "bump\n\nCo-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>",
    ).length,
    0,
  )
  assert.equal(textProblems("m", "Co-authored-by: Ann <ann@example.com>").length, 0)
})

test("noreply address, session link and generated footers are flagged", () => {
  assert.equal(textProblems("m", `x noreply@${A}.com`).length, 1)
  assert.equal(textProblems("m", `see https://${V}.ai/code/session_1`).length, 1)
  assert.equal(textProblems("m", `Generated with [${V} Code]`).length, 1)
  assert.equal(textProblems("m", `generated by [${V} code](u)`).length, 1)
  assert.equal(textProblems("m", "plain message about generated code").length, 0)
  assert.equal(textProblems("m", undefined).length, 0)
})

test("author and committer emails at the vendor domain are flagged", () => {
  const log = parseLog(
    ["abc1234", `a@${A}.com`, "ok@users.noreply.github.com", "subject"].join("\x1f") +
      "\x00" +
      ["def5678", "ok@x.com", `c@mail.${A}.com`, "subject"].join("\x1f") +
      "\x00",
  )
  assert.equal(log.length, 2)
  assert.equal(commitProblems(log).length, 2)
  assert.equal(
    commitProblems([{ sha: "1", authorEmail: `a@not${A}.com`, committerEmail: "", message: "" }])
      .length,
    0,
  )
})

test("PR title and body are checked from the event payload", () => {
  assert.equal(eventProblems({ pull_request: { title: "ok", body: "fine" } }).length, 0)
  assert.equal(
    eventProblems({ pull_request: { title: "ok", body: `Co-authored-by: ${V}` } }).length,
    1,
  )
  assert.equal(
    eventProblems({ pull_request: { title: `https://${V}.ai/code/x`, body: null } }).length,
    1,
  )
  assert.equal(eventProblems({}).length, 0)
})

test("a dependabot PR body that quotes a footer is not flagged", () => {
  const pr = {
    user: { login: "dependabot[bot]" },
    title: "bump x",
    body: `Generated with [${V} Code]`,
  }
  assert.equal(eventProblems({ pull_request: pr }).length, 0)
  assert.equal(eventProblems({ pull_request: { ...pr, user: { login: "ann" } } }).length, 1)
})

test("a zero or empty base checks only the head", () => {
  assert.deepEqual(rangeArgs("0000000000000000000000000000000000000000..abc"), [
    "-1",
    "--end-of-options",
    "abc",
  ])
  assert.deepEqual(rangeArgs("a..b"), ["--end-of-options", "a..b"])
  assert.throws(() => rangeArgs("a..b;rm"))
  assert.throws(() => rangeArgs("a..-p"))
  assert.throws(() => rangeArgs("-p..b"))
})

test("a bad range exits 2 without running git", () => {
  const lines = []
  assert.equal(main(["--range", "a..-p"], { out: (l) => lines.push(l) }), 2)
  assert.match(lines.join("\n"), /bad range/)
})

function repo() {
  const dir = mkdtempSync(join(tmpdir(), "attr-"))
  const git = (...a) =>
    execFileSync(
      "git",
      [
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@example.com",
        "-c",
        "core.hooksPath=/dev/null",
        ...a,
      ],
      { cwd: dir, encoding: "utf8" },
    ).trim()
  git("init", "-q")
  return { dir, git }
}

test("main passes a clean range and fails a bad commit in a temp repo", () => {
  const { dir, git } = repo()
  git("commit", "-q", "--allow-empty", "-m", "feat: first")
  const base = git("rev-parse", "HEAD")
  git("commit", "-q", "--allow-empty", "-m", "fix: clean")
  const old = process.cwd()
  process.chdir(dir)
  try {
    const lines = []
    assert.equal(main(["--range", `${base}..HEAD`], { out: (l) => lines.push(l) }), 0)
    git(
      "commit",
      "-q",
      "--allow-empty",
      "-m",
      `fix: bad\n\nCo-Authored-By: ${V} <noreply@${A}.com>`,
    )
    assert.equal(main(["--range", `${base}..HEAD`], { out: (l) => lines.push(l) }), 1)
    const event = join(dir, "event.json")
    writeFileSync(
      event,
      JSON.stringify({ pull_request: { title: "t", body: `Generated with [${V} Code]` } }),
    )
    assert.equal(main(["--range", `${base}..${base}`, "--event", event], { out: () => {} }), 1)
    assert.equal(
      main(["--range", `0000000000000000000000000000000000000000..${base}`], { out: () => {} }),
      0,
    )
    assert.equal(main([], { out: () => {} }), 2)
  } finally {
    process.chdir(old)
  }
})
