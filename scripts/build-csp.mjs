#!/usr/bin/env node
// Post-build step: computes CSP hashes for every inline <script> in public/**/*.html and writes
// them to worker/csp.generated.js, which worker/csp.js turns into the Content-Security-Policy
// header. (Styles are not hashed; see the comment in worker/csp.js.)
//
// Run after scripts/postprocess-build.mjs, because that script edits inline script text.
// Hashes use the exact text between the tags, which is what browsers hash.
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const pub = join(root, "public")
const out = join(root, "worker", "csp.generated.js")

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) yield* walk(full)
    else yield full
  }
}

const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`

// Script types that the browser executes. JSON data blocks (application/json, ld+json, ...) are
// not executed and need no hash.
const EXECUTABLE = /^(?:|module|(?:text|application)\/(?:javascript|ecmascript))$/i

const scripts = new Set()
const eventHandlers = []
let pages = 0

for (const file of walk(pub)) {
  if (!file.endsWith(".html")) continue
  pages++
  const html = readFileSync(file, "utf8")

  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1]
    if (/\ssrc\s*=/i.test(` ${attrs}`)) continue
    const type = /\stype\s*=\s*["']?([^"'\s>]*)/i.exec(` ${attrs}`)?.[1] ?? ""
    if (!EXECUTABLE.test(type) || m[2].trim() === "") continue
    scripts.add(sha256(m[2]))
  }
  for (const tag of html.matchAll(/<[a-z][^>]*>/gi)) {
    for (const m of tag[0].matchAll(/\s(on[a-z]+)\s*=/gi)) eventHandlers.push(`${file}: ${m[1]}`)
  }
}

if (pages === 0) {
  console.error("build-csp: no HTML found in public/; run the build first")
  process.exit(1)
}
if (eventHandlers.length > 0) {
  // Inline event handlers cannot be allowed without 'unsafe-inline'/'unsafe-hashes'; refuse them.
  console.error(`build-csp: inline event handlers found:\n  ${eventHandlers.join("\n  ")}`)
  process.exit(1)
}

const list = (set) => JSON.stringify([...set].sort(), null, 2)
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `// GENERATED by scripts/build-csp.mjs from public/**/*.html. Do not edit; not committed.
/** sha256 hashes of inline <script> contents. */
export const SCRIPT_HASHES = ${list(scripts)}
`,
)
console.log(`build-csp: ${pages} pages -> ${scripts.size} inline script hashes`)
